class UserProfileModel {
  final String fullName;
  final String email;
  final String phone;
  final String address;
  final double creditLimit;
  final String job;
  final String gender;

  UserProfileModel({
    required this.fullName,
    required this.email,
    required this.phone,
    required this.address,
    required this.creditLimit,
    required this.job,
    required this.gender,
  });
}
